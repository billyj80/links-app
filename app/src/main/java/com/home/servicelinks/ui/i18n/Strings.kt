    fun formatCategory(rawCategory: String): String {
        return when (rawCategory.trim().lowercase()) {
            "all" -> categoryAll
            "media" -> categoryMedia
            "server" -> categoryServer
            "storage" -> categoryStorage
            "monitoring" -> categoryMonitoring
            "development" -> categoryDevelopment
            "network" -> categoryNetwork
            "security" -> categorySecurity
            "automation" -> categoryAutomation
            "communication" -> categoryCommunication
            "database" -> categoryDatabase
            "other" -> categoryOther
            "smart home" -> if (categoryServer == "Serwer") "Inteligentny dom" else "Smart Home"
            "tools" -> if (categoryServer == "Serwer") "Narzędzia" else "Tools"
            "home" -> if (categoryServer == "Serwer") "Dom" else "Home"
            else -> rawCategory
        }
    }
}

